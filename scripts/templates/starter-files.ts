// The kickoff's view of scripts/site-template: every file, as a path → body
// map, in a TypeScript module the server bundle can import. Pure, so the test
// can rebuild it in memory and compare (scripts/test/starter-app.ts).
import { readdirSync, readFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

export const STARTER_DIR = "scripts/site-template";
export const STARTER_MODULE = "src/lib/starter-app.generated.ts";
const PIN = ".fleet-source";

function walk(dir: string, root: string, out: string[]): string[] {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, root, out);
    else if (entry.isFile()) out.push(relative(root, full).split(sep).join("/"));
  }
  return out;
}

export function starterModuleSource(root: string): string {
  const dir = join(root, STARTER_DIR);
  const source = readFileSync(join(dir, PIN), "utf8").trim();
  const files = walk(dir, dir, [])
    .filter((p) => p !== PIN)
    .sort();
  const entries = files.map(
    (p) => `  ${JSON.stringify(p)}: ${JSON.stringify(readFileSync(join(dir, p), "utf8"))},`,
  );
  return [
    "// GENERATED by scripts/templates/generate-starter-files.ts — do not edit.",
    "// scripts/site-template (= bitbaum/fleet templates/app at the commit below)",
    "// as a file map, so the kickoff can seed a repo from server code.",
    "// scripts/test/starter-app.ts fails when this and the directory differ.",
    `export const STARTER_APP_SOURCE = ${JSON.stringify(source)};`,
    "",
    "export const STARTER_APP_FILES: Readonly<Record<string, string>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

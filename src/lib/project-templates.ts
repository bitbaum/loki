// Project starter templates seeded by /api/projects/create-with-github when
// the user picks one. Each template is a small set of files that get committed
// to the brand-new repo in one Git Tree API call (single round-trip).
//
// Why inline files rather than a GitHub template-repo?
//   1. No external repo to maintain. Add a starter by editing this file.
//   2. Templates can include the user's chosen project name via {{NAME}}
//      placeholders — we substitute server-side before commit.
//   3. Single API call vs. forking + maintaining a template-repo on GitHub.
//
// Adding a starter: append a new TEMPLATES entry with its file map. Keep each
// starter small (< 15 files) so the commit stays under GitHub's tree-size
// limits and the choice list stays scannable.
//
// EXCEPT "nextjs-tailwind", which is not written here at all: it is the fleet
// starter (bitbaum/fleet templates/app), the same app new-site.sh scaffolds
// from scripts/site-template — see src/lib/starter-app.ts.

import { APP_URL } from "@/config/brand";
import { PROVISION_TEMPLATES, type ProvisionTemplateId } from "@/config/project-templates";
import { renderStarterFile, starterSeedFiles, starterValues } from "@/lib/starter-app";

/** Ids + labels come from the light config so pickers can import them without
 *  pulling every starter's file bodies into their bundle. */
export type TemplateId = ProvisionTemplateId;

export interface TemplateMeta {
  id: TemplateId;
  label: string;
  description: string;
  /** Map of repo-relative path → file contents. {{NAME}} is replaced with
   *  the slugged repo name; {{DESCRIPTION}} with the project description. */
  files: Record<string, string>;
  /** Human-readable infra the first agent task will set up on the user's
   *  machine — shown on the post-create bridge so the user sees what gets
   *  handled automatically (deps, database, dev server) vs. left to them. */
  infra: string[];
  /** The pre-composed first dispatch: an agent runs this to take the freshly
   *  cloned repo from "files exist" to "running locally", setting up everything
   *  the stack needs (dependencies, database + schema, dev server) — the
   *  auto-infra step, done where the code actually runs. {{NAME}} substituted. */
  firstTask: string;
  /** How a file body becomes the repo's file. Default: `renderTemplate`
   *  ({{NAME}} placeholders). The fleet starter uses its own (__SLUG__ …). */
  render?: (body: string, values: RenderValues) => string;
}

/** What a seed knows when it renders a file. */
export interface RenderValues {
  name: string;
  description: string;
  /** GitHub owner and repo the starter is being seeded into. */
  owner?: string;
  repo?: string;
}


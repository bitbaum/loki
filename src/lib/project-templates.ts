/** The full registry: light metadata (config) + what it seeds (above). */
export const TEMPLATES: Record<TemplateId, TemplateMeta> = Object.fromEntries(
  PROVISION_TEMPLATES.map((template) => [
    template.id,
    {
      id: template.id,
      label: template.label,
      description: template.description,
      ...TEMPLATE_BUILDS[template.id],
    },
  ]),
) as Record<TemplateId, TemplateMeta>;

/**
 * Substitute {{NAME}} / {{DESCRIPTION}} placeholders in a file body.
 * Kept tiny — no real templating engine. If we add more placeholders or
 * conditional blocks, lift to a proper templating step.
 */
export function renderTemplate(
  content: string,
  values: { name: string; description: string },
): string {
  const replacements: Record<string, string> = {
    NAME: values.name,
    DESCRIPTION: values.description,
    NAME_JSON: JSON.stringify(values.name),
    DESCRIPTION_JSON: JSON.stringify(values.description),
    SLUG_JSON: JSON.stringify(
      values.name
        .toLowerCase()
        .replace(/[^a-z0-9._-]+/g, "-")
        .replace(/^-+|-+$/g, ""),
    ),
  };
  return content.replace(
    /\{\{(NAME|DESCRIPTION|NAME_JSON|DESCRIPTION_JSON|SLUG_JSON)\}\}/g,
    (placeholder, key: string) => replacements[key] ?? placeholder,
  );
}
